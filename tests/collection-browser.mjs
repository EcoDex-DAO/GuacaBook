import { chromium } from "@playwright/test";
import assert from "node:assert/strict";
import JSZip from "jszip";
import { readFile } from "node:fs/promises";
import { A, B, rows, objects, setup, signIn, faults } from "./supabase-mock.mjs";
const browser = await chromium.launch({ executablePath: "/usr/bin/chromium", args: ["--no-sandbox", "--enable-unsafe-swiftshader"] });
try {
  const page = await browser.newPage({ locale: "fr-FR" });
  const png = await setup(page);
  const photoId = "33333333-3333-4333-8333-333333333333";
  for (const owner of [A, B]) {
    const photo = { id: photoId, name: "ara.png", objectPath: `${owner}/${photoId}`, mimeType: "image/png", width: 400, height: 300, capturedAt: "", sessionId: "session", birdId: "bird", quality: "usable", completed: true, viewpoint: null, bodyVisibility: "not_visible", eyeVisible: "no", boxes: [] };
    rows.set(owner, { owner_id: owner, revision: 1, status: owner === A ? "submitted" : "draft", consented_at: owner === A ? new Date().toISOString() : null,
      dataset: { profile: owner === A ? "Admin" : "Private", consent: owner === A, birds: [{ id: "bird", name: "Kiwi", species: "" }], photos: [photo] } });
    objects.set(photo.objectPath, Buffer.from(png, "base64"));
  }
  await page.goto(process.env.TEST_BASE_URL || "http://localhost:3000");
  await signIn(page, "a@example.com", key => key, "test-password-123", false);
  await page.locator(".research-consent").waitFor();
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.setViewportSize({ width: 1280, height: 900 });
  assert.equal(await page.getByLabel("Nom ou pseudonyme", { exact: true }).count(), 0);
  assert.equal(await page.getByRole("button", { name: "Accepter et continuer", exact: true }).isDisabled(), true);
  await page.locator('.research-consent input[type="checkbox"]').check();
  faults.writes = 1;
  await page.getByRole("button", { name: "Accepter et continuer", exact: true }).click();
  await page.locator(".research-consent [role=alert]").waitFor();
  await page.getByRole("button", { name: "Accepter et continuer", exact: true }).click();
  await page.locator(".research-consent").waitFor({ state: "hidden" });
  assert.equal(rows.get(A).dataset.researchConsent.version, "guacabook-research-v1");
  assert.ok(rows.get(A).dataset.researchConsent.acceptedAt);
  await page.getByRole("heading", { name: "Kiwi", exact: true }).waitFor();
  await page.getByText("Administration des contributions", { exact: true }).click();
  async function archive(button) {
    const pending = page.waitForEvent("download");
    await page.getByRole("button", { name: button, exact: true }).click();
    const download = await pending;
    return JSZip.loadAsync(await readFile(await download.path()));
  }
  const raw = await archive("Exporter tous les originaux pour vérification");
  assert.equal(Object.values(raw.files).filter(f => !f.dir && f.name.startsWith("images/")).length, 2);
  const final = await archive("Exporter V1 (COCO + Wild Me)");
  const coco = JSON.parse(await final.file("annotations.json").async("string"));
  assert.equal(coco.images.length, 1);
  assert.ok(final.file(coco.images[0].file_name));
  assert.ok(coco.images[0].file_name.includes(A));
  assert.equal(JSON.parse(await final.file("manifest.json").async("string")).collections.length, 1);
  page.on("dialog", dialog => { if (dialog.type() === "beforeunload") return dialog.accept(); throw new Error("Native blocking confirmation must not be used"); });
  await page.getByRole("button", { name: "Supprimer cet animal", exact: true }).click();
  await page.getByRole("dialog").waitFor();
  await page.getByRole("button", { name: "Annuler", exact: true }).click();
  assert.equal(rows.get(A).dataset.birds.length, 1);
  await page.getByRole("button", { name: "Supprimer cet animal", exact: true }).click();
  faults.deletes = 2;
  await page.getByRole("button", { name: "Supprimer définitivement", exact: true }).click();
  await page.getByRole("button", { name: "Réessayer la suppression", exact: true }).waitFor();
  assert.equal(rows.get(A).dataset.birds.length, 0);
  assert.equal(rows.get(A).dataset.photos.length, 0);
  assert.deepEqual(rows.get(A).dataset.deletedPhotoIds, [photoId]);
  assert.ok(objects.has(`${A}/${photoId}`));
  await page.getByRole("button", { name: "Réessayer la suppression", exact: true }).click();
  await page.getByRole("button", { name: "Réessayer la suppression", exact: true }).waitFor();
  await page.reload();
  await page.locator(".beta-notice").waitFor();
  await page.waitForResponse(response => response.request().method() === "DELETE" && response.url().includes("storage/v1/object"));
  await page.getByRole("status").filter({ hasText: "Toutes les modifications sont enregistrées en ligne." }).first().waitFor();
  assert.equal(objects.has(`${A}/${photoId}`), false);
  assert.equal(rows.get(A).dataset.photos.length, 0);
  assert.deepEqual(rows.get(A).dataset.deletedPhotoIds, []);
  assert.equal(await page.getByRole("heading", { name: "Kiwi", exact: true }).count(), 0);
  assert.equal(await page.locator(".research-consent").count(), 0);
  await page.getByRole("button", { name: "Se déconnecter", exact: true }).click();
  await signIn(page, "b@example.com");
  await page.getByRole("heading", { name: "Kiwi", exact: true }).waitFor();
  assert.equal(await page.getByText("Administration des contributions", { exact: true }).count(), 0);
  assert.equal(await page.locator(".cloudpanel").count(), 0);
  assert.equal(await page.getByRole("button", { name: "Soumettre ma collection à la recherche", exact: true }).count(), 0);
  console.log("PASS: confirmation/cancel, full persisted deletion with retry and cleanup after reload, global review/final ZIP contents, contributor UI isolation (simulated API).");
} finally { await browser.close(); }
